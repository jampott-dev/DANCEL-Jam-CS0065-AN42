# Import required libraries
import nltk
import re
import html
import ipywidgets as widgets
from nltk.corpus import opinion_lexicon
from IPython.display import display, HTML, clear_output

# Download dataset
nltk.download('opinion_lexicon')

# Get positive and negative words
positive_words = set(opinion_lexicon.positive())
negative_words = set(opinion_lexicon.negative())

# Function to count positive words
def number_happy(sentence):
    words = re.findall(r"[a-zA-Z]+", sentence.lower())
    count = 0

    for word in words:
        if word in positive_words:
            count += 1

    return count

# Function to count negative words
def number_sad(sentence):
    words = re.findall(r"[a-zA-Z]+", sentence.lower())
    count = 0

    for word in words:
        if word in negative_words:
            count += 1

    return count

# Create input field and buttons
sentence_input = widgets.Text(
    placeholder="Enter your sentence here...",
    description="Sentence:",
    layout=widgets.Layout(width="80%")
)

analyze_button = widgets.Button(
    description="Analyze Sentence",
    button_style="success"
)

yes_button = widgets.Button(
    description="Yes",
    button_style="success"
)

no_button = widgets.Button(
    description="No",
    button_style="danger"
)

output = widgets.Output()

# Function to display word references
def display_words():

    positive_html = "".join(
        f"<div>{html.escape(word)}</div>"
        for word in sorted(positive_words)
    )

    negative_html = "".join(
        f"<div>{html.escape(word)}</div>"
        for word in sorted(negative_words)
    )

    display(HTML(f"""
    <div style="
        display: flex;
        justify-content: center;
        gap: 30px;
        width: 100%;
        font-family: Arial;
    ">

        <div style="
            flex: 1;
            height: 350px;
            box-sizing: border-box;
            border: 4px solid #28a745;
            border-radius: 55px;
            padding: 20px;
            text-align: center;
            overflow-y: auto;
        ">
            <h2 style="color: #28a745;">POSITIVE</h2>
            <div style="text-align: left; line-height: 1.8;">
                {positive_html}
            </div>
        </div>

        <div style="
            flex: 1;
            height: 350px;
            box-sizing: border-box;
            border: 4px solid #dc3545;
            border-radius: 55px;
            padding: 20px;
            text-align: center;
            overflow-y: auto;
        ">
            <h2 style="color: #dc3545;">NEGATIVE</h2>
            <div style="text-align: left; line-height: 1.8;">
                {negative_html}
            </div>
        </div>

    </div>
    """))

# Function to analyze the sentence
def analyze_sentence(button):

    sentence = sentence_input.value.strip()

    if not sentence:
        with output:
            clear_output(wait=True)
            print("Please enter a sentence first.")
        return

    happy = number_happy(sentence)
    sad = number_sad(sentence)

    with output:
        clear_output(wait=True)

        # Display analysis
        print("========== SENTENCE ANALYSIS ==========")
        print("Number of positive words:", happy)
        print("Number of negative words:", sad)

        if happy > sad:
            print("\nThe tone of the sentence is POSITIVE.")

        elif sad > happy:
            print("\nThe tone of the sentence is NEGATIVE.")

        else:
            print("\nThe tone of the sentence is NEUTRAL.")

        print("=======================================")

        # Display follow-up question
        print("\nWant to enter a new sentence?")

        display(widgets.HBox([yes_button, no_button]))

        # Display word references
        print("\n========== WORD REFERENCES ==========")
        display_words()

# Function for Yes button
def enter_new_sentence(button):

    sentence_input.value = ""

    with output:
        clear_output(wait=True)
        print("Enter a new sentence above and click Analyze Sentence.")

# Function for No button
def exit_program(button):

    sentence_input.value = ""

    with output:
        clear_output(wait=True)
        print("Exit program.")

# Connect buttons to functions
analyze_button.on_click(analyze_sentence)
yes_button.on_click(enter_new_sentence)
no_button.on_click(exit_program)

# Display the program interface
display(widgets.VBox([
    sentence_input,
    analyze_button,
    output
]))
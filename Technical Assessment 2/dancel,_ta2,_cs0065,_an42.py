# ==========================================

def run_standard_simulation():
    print("="*50)
    print("      STANDARD SIMULATION (2 ROOMS: A & B)      ")
    print("="*50)

    # 1. Environment Setup
    state_a = input("Enter initial state for Room A (Dirty/Clean): ").strip().capitalize()
    state_b = input("Enter initial state for Room B (Dirty/Clean): ").strip().capitalize()

    environment = {
        "A": state_a if state_a in ["Dirty", "Clean"] else "Dirty",
        "B": state_b if state_b in ["Dirty", "Clean"] else "Dirty"
    }

    start_loc = input("Enter starting room for Agent (A/B): ").strip().upper()
    if start_loc not in ["A", "B"]:
        start_loc = "A"

    steps = int(input("Enter number of simulation steps: "))

    agent = VacuumAgent(current_location=start_loc)

    print("\nStarting 2-Room Simulation...")
    print(f"Initial State: {environment}\n")

    for step in range(1, steps + 1):
        action = agent.perceive_and_act(environment, is_three_rooms=False)
        print(f"Step {step}:")
        print(f"  Agent Location: Room {agent.current_location}")
        print(f"  Action Taken  : {action}")
        print(f"  Env State     : {environment}")
        print("-" * 40)

def run_bonus_simulation():
    print("\n" + "="*50)
    print("      BONUS SIMULATION (3 ROOMS: A, B & C)      ")
    print("="*50)

    state_a = input("Enter initial state for Room A (Dirty/Clean): ").strip().capitalize()
    state_b = input("Enter initial state for Room B (Dirty/Clean): ").strip().capitalize()
    state_c = input("Enter initial state for Room C (Dirty/Clean): ").strip().capitalize()

    environment = {
        "A": state_a if state_a in ["Dirty", "Clean"] else "Dirty",
        "B": state_b if state_b in ["Dirty", "Clean"] else "Dirty",
        "C": state_c if state_c in ["Dirty", "Clean"] else "Dirty"
    }

    start_loc = input("Enter starting room for Agent (A/B/C): ").strip().upper()
    if start_loc not in ["A", "B", "C"]:
        start_loc = "A"

    steps = int(input("Enter number of simulation steps: "))

    agent = VacuumAgent(current_location=start_loc)

    print("\nStarting 3-Room Visual Simulation...")
    render_grid(environment, agent.current_location)

    for step in range(1, steps + 1):
        time.sleep(0.5) # Brief pause for step display
        action = agent.perceive_and_act(environment, is_three_rooms=True)
        print(f"\nStep {step}: {action}")
        render_grid(environment, agent.current_location)

